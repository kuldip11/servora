import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const checkOnly = args.includes("--check");
const input = args.find((arg) => arg !== "--check") ?? process.env.SERVORA_OPENAPI_SOURCE ?? "http://127.0.0.1:5175/swagger/json";
const output = resolve("packages/api-client/src/generated/openapi-contract.ts");

const loadSpec = async () => {
  if (/^https?:\/\//.test(input)) {
    const response = await fetch(input);
    if (!response.ok) throw new Error(`OpenAPI fetch failed (${response.status}) from ${input}`);
    return response.json();
  }
  return JSON.parse(await readFile(resolve(input), "utf8"));
};

const spec = await loadSpec();
const methods = new Set(["get", "post", "put", "patch", "delete", "options", "head"]);
const operations = [];
for (const [path, definition] of Object.entries(spec.paths ?? {})) {
  for (const method of Object.keys(definition ?? {})) {
    if (methods.has(method)) operations.push({ method: method.toUpperCase(), path });
  }
}
operations.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const lines = [
  "// AUTO-GENERATED by scripts/contracts/generate-openapi-contract.mjs.",
  "// Do not hand-edit. Regenerate from Servora /swagger/json.",
  "",
  `export const OPENAPI_VERSION = ${JSON.stringify(spec.info?.version ?? "unknown")} as const;`,
  "",
  "export const OPENAPI_OPERATIONS = [",
  ...operations.map(({ method, path }) => `  { method: ${JSON.stringify(method)}, path: ${JSON.stringify(path)} },`),
  "] as const;",
  "",
  "export type OpenApiOperation = (typeof OPENAPI_OPERATIONS)[number];",
  "export type OpenApiMethod = OpenApiOperation[\"method\"];",
  "export type OpenApiPath = OpenApiOperation[\"path\"];",
  "",
];

const generated = `${lines.join("\n")}\n`;
await mkdir(resolve("packages/api-client/src/generated"), { recursive: true });
if (checkOnly) {
  let current = "";
  try { current = await readFile(output, "utf8"); } catch {}
  if (current !== generated) {
    console.error("Generated OpenAPI contract is stale. Run `bun run contracts:generate` and commit the result.");
    process.exit(1);
  }
  console.log(`OpenAPI contract is current (${operations.length} operations).`);
} else {
  await writeFile(output, generated);
  console.log(`Generated ${operations.length} OpenAPI operations -> ${output}`);
}
